import { formatMetric } from "@/lib/reports/format";
import type { ReportContent } from "@/lib/reports/types";

interface ReportPaperProps {
  content: ReportContent | null;
  /** Why there's no preview (a missing metric, channel or bad window). */
  problem: string | null;
  loading: boolean;
}

const TOP = 8;

function Table({ content, title, rows }: { content: ReportContent; title: string; rows: { label: string; detail?: string; values: (number | null)[]; total?: boolean }[] }) {
  return (
    <div className="cor-paper__section">
      <span className="cor-paper__heading">{title}</span>
      <table className="cor-paper__table">
        <thead><tr><th scope="col"><span className="cor-visually-hidden">Name</span></th>{content.metrics.map((metric) => <th key={metric.key} scope="col">{metric.label}</th>)}</tr></thead>
        <tbody>
          {rows.map((row) => (
            <tr key={`${row.label}${row.detail ?? ""}`} className={row.total ? "cor-paper__total" : undefined}>
              <th scope="row">{row.label}{row.detail && <span> {row.detail}</span>}</th>
              {content.metrics.map((metric, i) => <td key={metric.key}>{formatMetric(metric.key, row.values[i], content.currency)}</td>)}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}

/** The report as the PDF lays it out, always on light paper. */
export function ReportPaper({ content, problem, loading }: ReportPaperProps) {
  return (
    <section className="cor-report-preview" aria-label="Preview" aria-busy={loading}>
      <span className="cor-tag">Preview{loading ? " · updating…" : ""}</span>
      <div className="cor-paper cor-paper--report" data-theme="light">
        {problem || !content ? <p className="cor-paper__empty">{problem ?? "Pick metrics and channels to see the report."}</p> : (
          <>
            <span className="cor-paper__brand">COR report</span>
            <h2 className="cor-paper__title">{content.title}</h2>
            <span className="cor-paper__meta">{[content.windowLabel, content.previousLabel].filter(Boolean).join(" · ")}</span>
            <span className="cor-paper__meta cor-paper__meta--muted">{content.channelNames.join(", ")} · {content.sourceLabel}</span>
            {content.empty ? (
              <p className="cor-paper__empty">No data for {content.windowLabel} on {content.channelNames.join(", ") || "those channels"}. Pick a wider window or more channels.</p>
            ) : (
              <>
                <dl className="cor-paper__summary" style={{ gridTemplateColumns: `repeat(${Math.min(content.summary.length, 4)}, minmax(0, 1fr))` }}>
                  {content.summary.map((item) => (
                    <div key={item.key}><dt>{item.label}</dt><dd>{item.value}</dd>{item.change && <dd className={`cor-paper__change cor-paper__change--${item.tone}`}>{item.change}</dd>}</div>
                  ))}
                </dl>
                <Table content={content} title="By channel" rows={[...content.byChannel.map((row) => ({ label: row.name, values: row.values })), { label: "Total", values: content.total, total: true }]} />
                <Table content={content} title={content.campaigns.length > TOP ? `Top ${TOP} campaigns` : "Campaigns"} rows={content.campaigns.slice(0, TOP).map((row) => ({ label: row.name, detail: row.channel, values: row.values }))} />
              </>
            )}
            <span className="cor-paper__foot">Generated by COR on {content.generatedOn}</span>
          </>
        )}
      </div>
    </section>
  );
}

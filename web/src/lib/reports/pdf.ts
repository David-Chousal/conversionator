import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from "pdf-lib";
import { formatMetric } from "./format";
import type { ReportContent } from "./types";

const PAGE = { width: 612, height: 792, margin: 48 };
const INK = rgb(0.07, 0.09, 0.11);
const MUTED = rgb(0.42, 0.47, 0.5);
const RULE = rgb(0.85, 0.88, 0.88);
const VALUE_COLUMN = 76;
const ROW = 18;
const TOP_CAMPAIGNS = 25;

// The standard PDF fonts only cover WinAnsi; swap the app's typographic characters for ones they can draw.
const UNSUPPORTED = /[^\x20-\x7E -ÿ–—‘’“”•…€]/g;
const safe = (text: string) => text.replace(/→/g, "–").replace(/−/g, "-").replace(UNSUPPORTED, "?");

interface Pen {
  doc: PDFDocument;
  page: PDFPage;
  y: number;
  regular: PDFFont;
  bold: PDFFont;
}

function text(pen: Pen, value: string, x: number, size: number, options: { bold?: boolean; color?: typeof INK; right?: number; width?: number } = {}) {
  const font = options.bold ? pen.bold : pen.regular;
  let line = safe(value);
  while (options.width && line.length > 1 && font.widthOfTextAtSize(line, size) > options.width) line = `${line.slice(0, -2)}…`;
  const drawX = options.right === undefined ? x : options.right - font.widthOfTextAtSize(line, size);
  pen.page.drawText(line, { x: drawX, y: pen.y, size, font, color: options.color ?? INK });
}

const rule = (pen: Pen, weight = 0.5, color = RULE) =>
  pen.page.drawLine({ start: { x: PAGE.margin, y: pen.y }, end: { x: PAGE.width - PAGE.margin, y: pen.y }, thickness: weight, color });

function ensureRoom(pen: Pen, needed: number) {
  if (pen.y - needed > PAGE.margin + 24) return;
  pen.page = pen.doc.addPage([PAGE.width, PAGE.height]);
  pen.y = PAGE.height - PAGE.margin;
}

function header(pen: Pen, content: ReportContent) {
  text(pen, "COR REPORT", PAGE.margin, 8, { color: MUTED });
  pen.y -= 28;
  text(pen, content.title, PAGE.margin, 22, { bold: true, width: PAGE.width - PAGE.margin * 2 });
  pen.y -= 18;
  text(pen, [content.windowLabel, content.previousLabel].filter(Boolean).join(" · "), PAGE.margin, 10);
  pen.y -= 14;
  text(pen, `${content.channelNames.join(", ")} · ${content.sourceLabel}`, PAGE.margin, 9, { color: MUTED, width: PAGE.width - PAGE.margin * 2 });
  pen.y -= 20;
}

function summary(pen: Pen, content: ReportContent) {
  rule(pen, 2, INK);
  const width = (PAGE.width - PAGE.margin * 2) / Math.max(1, content.summary.length);
  pen.y -= 14;
  content.summary.forEach((item, i) => text(pen, item.label.toUpperCase(), PAGE.margin + i * width, 7, { color: MUTED, width: width - 8 }));
  pen.y -= 20;
  content.summary.forEach((item, i) => text(pen, item.value, PAGE.margin + i * width, 16, { bold: true, width: width - 8 }));
  pen.y -= 14;
  content.summary.forEach((item, i) => item.change && text(pen, item.change, PAGE.margin + i * width, 8, { color: MUTED }));
  pen.y -= 28;
}

/** The row's name, then its channel in muted text when there's room. */
function label(pen: Pen, row: { label: string; detail?: string; bold?: boolean }, width: number) {
  const nameWidth = row.detail ? width * 0.7 : width;
  text(pen, row.label, PAGE.margin, 9, { bold: row.bold, width: nameWidth });
  if (!row.detail) return;
  const used = Math.min(nameWidth, (row.bold ? pen.bold : pen.regular).widthOfTextAtSize(safe(row.label), 9));
  text(pen, row.detail, PAGE.margin + used + 10, 8, { color: MUTED, width: width - used - 10 });
}

function table(pen: Pen, content: ReportContent, title: string, rows: { label: string; detail?: string; values: (number | null)[]; bold?: boolean }[]) {
  ensureRoom(pen, ROW * 4);
  rule(pen, 2, INK);
  pen.y -= 16;
  text(pen, title, PAGE.margin, 11, { bold: true });
  pen.y -= 18;
  const right = (i: number) => PAGE.width - PAGE.margin - (content.metrics.length - 1 - i) * VALUE_COLUMN;
  const nameWidth = PAGE.width - PAGE.margin * 2 - content.metrics.length * VALUE_COLUMN - 8;
  content.metrics.forEach((metric, i) => text(pen, metric.label.toUpperCase(), 0, 7, { color: MUTED, right: right(i), width: VALUE_COLUMN - 6 }));
  pen.y -= 6;
  rule(pen);
  for (const row of rows) {
    ensureRoom(pen, ROW);
    pen.y -= ROW - 5;
    label(pen, row, nameWidth);
    content.metrics.forEach((metric, i) => text(pen, formatMetric(metric.key, row.values[i], content.currency), 0, 9, { bold: row.bold, right: right(i) }));
    pen.y -= 5;
    rule(pen);
  }
  pen.y -= 24;
}

function footers(doc: PDFDocument, font: PDFFont, content: ReportContent) {
  const pages = doc.getPages();
  pages.forEach((page, i) => {
    page.drawText(safe(`Generated by COR on ${content.generatedOn}`), { x: PAGE.margin, y: PAGE.margin - 16, size: 7, font, color: MUTED });
    const label = `Page ${i + 1} of ${pages.length}`;
    page.drawText(label, { x: PAGE.width - PAGE.margin - font.widthOfTextAtSize(label, 7), y: PAGE.margin - 16, size: 7, font, color: MUTED });
  });
}

/** A letter-size PDF: header, summary, totals by channel and the top campaigns. */
export async function reportPdf(content: ReportContent): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(safe(content.title));
  doc.setCreator("COR");
  const pen: Pen = { doc, page: doc.addPage([PAGE.width, PAGE.height]), y: PAGE.height - PAGE.margin, regular: await doc.embedFont(StandardFonts.Helvetica), bold: await doc.embedFont(StandardFonts.HelveticaBold) };
  header(pen, content);
  summary(pen, content);
  table(pen, content, "By channel", [...content.byChannel.map((row) => ({ label: row.name, values: row.values })), { label: "Total", values: content.total, bold: true }]);
  const top = content.campaigns.slice(0, TOP_CAMPAIGNS);
  table(pen, content, content.campaigns.length > TOP_CAMPAIGNS ? `Top ${TOP_CAMPAIGNS} campaigns by spend` : "Campaigns by spend", top.map((row) => ({ label: row.name, detail: row.channel, values: row.values })));
  footers(doc, pen.regular, content);
  return doc.save();
}
